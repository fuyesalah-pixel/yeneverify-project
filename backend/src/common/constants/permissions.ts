import type { Role } from './roles';

// Mirror of shared/contracts/roles.json permission matrix.
// Source of truth for RBAC checks across the application.
export const PERMISSIONS = {
  VERIFY_PAYMENT: 'VERIFY_PAYMENT',
  VIEW_OWN_VERIFICATIONS: 'VIEW_OWN_VERIFICATIONS',
  VIEW_ALL_BRANCH_DATA: 'VIEW_ALL_BRANCH_DATA',
  CREATE_SUB_MERCHANTS: 'CREATE_SUB_MERCHANTS',
  MANAGE_SUB_MERCHANT_PERMISSIONS: 'MANAGE_SUB_MERCHANT_PERMISSIONS',
  VIEW_ANALYTICS: 'VIEW_ANALYTICS',
  EXPORT_REPORTS: 'EXPORT_REPORTS',
  MANAGE_SUBSCRIPTION: 'MANAGE_SUBSCRIPTION',
  VIEW_ALL_MERCHANTS: 'VIEW_ALL_MERCHANTS',
  MANAGE_BANKS_AND_APIS: 'MANAGE_BANKS_AND_APIS',
  BAN_USERS_HANDLE_FRAUD: 'BAN_USERS_HANDLE_FRAUD',
  VIEW_OWN_AUDIT_LOG: 'VIEW_OWN_AUDIT_LOG',
} as const;

export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];

/** Which roles have each permission. */
export const ROLE_PERMISSIONS: Record<Permission, Role[]> = {
  VERIFY_PAYMENT: ['ADMIN', 'MERCHANT', 'SUB_MERCHANT'],
  VIEW_OWN_VERIFICATIONS: ['ADMIN', 'MERCHANT', 'SUB_MERCHANT'],
  VIEW_ALL_BRANCH_DATA: ['ADMIN', 'MERCHANT'],
  CREATE_SUB_MERCHANTS: ['ADMIN', 'MERCHANT'],
  MANAGE_SUB_MERCHANT_PERMISSIONS: ['ADMIN', 'MERCHANT'],
  VIEW_ANALYTICS: ['ADMIN', 'MERCHANT'],
  EXPORT_REPORTS: ['ADMIN', 'MERCHANT'],
  MANAGE_SUBSCRIPTION: ['ADMIN', 'MERCHANT'],
  VIEW_ALL_MERCHANTS: ['ADMIN'],
  MANAGE_BANKS_AND_APIS: ['ADMIN'],
  BAN_USERS_HANDLE_FRAUD: ['ADMIN'],
  VIEW_OWN_AUDIT_LOG: ['ADMIN', 'MERCHANT', 'SUB_MERCHANT'],
};

export function hasPermission(role: Role, permission: Permission): boolean {
  return ROLE_PERMISSIONS[permission].includes(role);
}
