#!/usr/bin/env bash
# Regenerate docs/ops/environment.md from the committed backend example file.
# The parser intentionally uses only variable names and example metadata; it
# never reads backend/.env and never emits a real secret.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/backend/.env.example"
OUTPUT_FILE="$ROOT_DIR/docs/ops/environment.md"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "ERROR: missing $ENV_FILE" >&2
  exit 1
fi
mkdir -p "$(dirname "$OUTPUT_FILE")"

node - "$ENV_FILE" "$OUTPUT_FILE" <<'NODE'
const fs = require('node:fs');

const [envPath, outputPath] = process.argv.slice(2);
const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/);
const entries = [];
let group = 'General';
let metadata = '';

for (const line of lines) {
  const groupMatch = line.match(/^#\s*-{4,}\s*(.*?)\s*-{4,}\s*$/);
  if (groupMatch) {
    group = groupMatch[1].trim();
    metadata = '';
    continue;
  }

  const commentMatch = line.match(/^#\s*\[(public|config|secret)\]\s*(.*)$/i);
  if (commentMatch) {
    metadata = `${commentMatch[1].toLowerCase()}|${commentMatch[2]}`;
    continue;
  }

  const assignmentMatch = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
  if (!assignmentMatch) continue;

  const [, key, rawValue] = assignmentMatch;
  const parts = metadata.split('|').map((part) => part.trim());
  const sensitivity = parts[0] || 'config';
  const type = (parts[1] || '').replace(/^type=/i, '') || 'string';
  const requiredValue = (parts[2] || '').replace(/^required=/i, '') || 'see schema';
  const required = requiredValue === 'false' ? 'no' : requiredValue === 'true' ? 'yes' : requiredValue;
  const fourthPart = parts[3] || '';
  const defaultValue = fourthPart.startsWith('default=')
    ? fourthPart.replace(/^default=/i, '')
    : '—';
  const description = parts.slice(4).join(' | ') || 'See backend/.env.example comment.';
  const example = rawValue === '' ? 'empty' : rawValue;

  entries.push({
    group,
    key,
    sensitivity,
    type,
    required,
    defaultValue,
    example,
    description,
  });
}

function cell(value) {
  return String(value)
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, '<br>')
    .replace(/`/g, "'");
}

const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
const existingDate = existing.match(/^> Last updated: (\d{4}-\d{2}-\d{2})/m)?.[1];
const today = process.env.DOC_DATE || existingDate || new Date().toISOString().slice(0, 10);
const out = [];
out.push('# Environment Variables');
out.push('');
out.push(`> Last updated: ${today} | Owner: Kiro`);
out.push('> Generated by `./scripts/gen-env-docs.sh`; edit `backend/.env.example`, not this file.');
out.push('');
out.push('Backend values are validated at boot by `backend/src/config/env.schema.ts`.');
out.push('`[secret]` values are never printed, logged, committed, or sent to the mobile app.');
out.push('');

let currentGroup = '';
for (const entry of entries) {
  if (entry.group !== currentGroup) {
    if (currentGroup) out.push('');
    out.push(`## ${entry.group}`);
    out.push('');
    out.push('| Name | Type | Required | Default | Example | Sensitivity | Description |');
    out.push('|---|---|---|---|---|---|---|');
    currentGroup = entry.group;
  }
  out.push(
    `| \`${cell(entry.key)}\` | ${cell(entry.type)} | ${cell(entry.required)} | ${cell(entry.defaultValue)} | ${cell(entry.example)} | ${cell(entry.sensitivity)} | ${cell(entry.description)} |`,
  );
}

out.push('');
out.push('## Per-environment behavior');
out.push('');
out.push('| Key/behavior | Local development | Staging | Production |');
out.push('|---|---|---|---|');
out.push('| `NODE_ENV` | `development` | `staging` | `production` |');
out.push('| `LOG_LEVEL` | `debug` | `info` | `warn` |');
out.push('| Database | Docker PostgreSQL | Hostinger managed PostgreSQL | Hostinger managed PostgreSQL |');
out.push('| Redis | Docker Redis | Hostinger Redis | Hostinger Redis |');
out.push('| R2 | MinIO via `R2_USE_MINIO=true` | Cloudflare R2 staging bucket | Cloudflare R2 production bucket |');
out.push('| AfroMessage | deterministic mock | real sandbox key | real production key |');
out.push('| Vision OCR | deterministic mock | GCP staging project | GCP production project |');
out.push('| FCM | disabled/mock | real staging project | real production project |');
out.push('| Sentry | disabled by empty DSN | staging DSN | production DSN |');
out.push('| Throttle | relaxed local override (`THROTTLE_LIMIT=1000`) | real values | real values, stricter OTP limit |');
out.push('| JWT keys | development key | staging key | production key, different from staging |');
out.push('| Bank adapters | mock registry | real, low concurrency | real, configured concurrency |');
out.push('| Feature flags | all MVP flags on | conservative | conservative |');
out.push('');
out.push('## Injection rules');
out.push('');
out.push('- Local: copy `docker/.env.example` to `docker/.env`; `bootstrap.sh` passes it to Compose.');
out.push('- Local backend: copy `backend/.env.example` to `backend/.env`; NestJS loads dotenv only for this local workflow.');
out.push('- Staging/production: inject values through Hostinger. Never copy a production `.env` into the repository.');
out.push('- Hosted `APP_URL`, `CORS_ORIGINS`, `R2_ENDPOINT`, and `R2_PUBLIC_BASE_URL` must be real HTTPS endpoints; localhost and wildcards are rejected in production.');
out.push('- File-backed credentials use read-only mounts under `/run/secrets`; environment values contain paths, not JSON contents.');
out.push('- `FCM_PRIVATE_KEY_FILE` takes precedence over the escaped `FCM_PRIVATE_KEY` value when a file mount is configured.');
out.push('- Run `./scripts/check-env-sync.sh` after changing the example or schema.');
out.push('');
out.push('See [rotation.md](rotation.md), [secrets.md](secrets.md), and [deploy.md](deploy.md) for operational policy.');

fs.writeFileSync(outputPath, `${out.join('\n')}\n`, 'utf8');
console.log(`Generated ${outputPath} (${entries.length} variables).`);
NODE
